import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

// --- Configuration ---
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");
const TEMPLATE_DIR = path.join(ROOT, "src", "template");
const SCRIPT_DIR = path.join(TEMPLATE_DIR, "script");
const OUTPUT_FILE = path.join(ROOT, "src", "libs", "templates", "registry.ts");

const TEMPLATE_EXT = ".ejs";
const SCRIPT_EXT = ".js";

// --check: fail instead of writing when the registry is out of date.
const CHECK = process.argv.includes("--check");

// --- Helpers ---

/** Escape a string so it is safe inside a JS template literal. */
function escapeTemplateLiteral(str) {
  return str
    .replace(/\\/g, "\\\\") // escape backslashes first
    .replace(/`/g, "\\`") // escape backticks
    .replace(/\$\{/g, "\\${"); // escape ${ interpolations
}

/** Read and sort all files with the given extension from a directory. */
function readFiles(dir, ext) {
  const entries = new Map();

  if (!fs.existsSync(dir)) {
    throw new Error(`[build-templates] Directory not found: ${dir}`);
  }

  const files = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(ext))
    .sort();

  for (const file of files) {
    const name = path.basename(file, ext);
    const content = fs.readFileSync(path.join(dir, file), "utf-8");
    entries.set(name, content);
  }

  return entries;
}

/** Build a Record<string, string> block for the generated file. */
function buildRecord(entries) {
  if (entries.size === 0) return "{}";

  const lines = [];
  for (const [name, content] of entries) {
    const escaped = escapeTemplateLiteral(content);
    lines.push(`  "${name}": \`${escaped}\``);
  }
  return "{\n" + lines.join(",\n") + ",\n}";
}

// --- Main ---

const templates = readFiles(TEMPLATE_DIR, TEMPLATE_EXT);
const scripts = readFiles(SCRIPT_DIR, SCRIPT_EXT);

const output = [
  "// Auto-generated by scripts/build-templates.mjs — DO NOT EDIT",
  "// Regenerated by `npm run build`; edit the files in src/template instead.",
  "",
  `export const templates: Record<string, string> = ${buildRecord(templates)};`,
  "",
  `export const scripts: Record<string, string> = ${buildRecord(scripts)};`,
  "",
].join("\n");

const relativeOutput = path.relative(ROOT, OUTPUT_FILE);
const current = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, "utf-8") : null;

if (CHECK) {
  if (current !== output) {
    console.error(
      `[build-templates] ${relativeOutput} is out of date with src/template. Run \`npm run build:templates -w girk-sdk\`.`,
    );
    process.exit(1);
  }
  console.log(`[build-templates] ${relativeOutput} is up to date.`);
} else if (current !== output) {
  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, output, "utf-8");
  console.log(
    `[build-templates] Wrote ${relativeOutput} (${templates.size} templates, ${scripts.size} scripts).`,
  );
}
